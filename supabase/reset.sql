--  重置資料庫：回到「從來沒有人使用過」的狀態
--
--  ⚠ 這些操作會刪除資料，而且無法復原。
--    要保留紀錄的話，請先到後台「明細」最下方按「匯出」，下載 CSV。
--  ⚠ 建議只在「測試用」的 Supabase 專案使用。
--    給她正式使用的專案，從她開卡之後就不要執行這個檔案。
--
--  使用方式（Supabase Dashboard → SQL Editor → New query）：
--    1. 整份貼上。目前只有【選項 A】是啟用的（沒有被 -- 註解掉）。
--    2. 想用別的選項時，先把【選項 A】那一行前面加上 --（註解掉），
--       再把想用的選項前面的 -- 拿掉，然後按 Run。
--    3. 一次只啟用一個選項。
--    4. 執行後，下方 Results 會顯示新的通行碼，只會顯示這一次，請立刻複製存好。
--
--  選項一覽
--    選項 A  重置卡片（最常用）        清空資料：是   她的通行碼：換新   後台通行碼：不變
--    選項 B  完整重置（卡片＋兩組碼）  清空資料：是   她的通行碼：換新   後台通行碼：換新
--    選項 C  只換後台通行碼            清空資料：否   她的通行碼：不變   後台通行碼：換新
--    選項 D  整套砍掉重建              清空資料：是   她的通行碼：換新   後台通行碼：換新（資料庫結構也會刪掉重建）
--
--  選項 B、C 用到的 app.reset_all()、app.rotate_admin_token() 是後來才新增的函式。
--  如果你的資料庫是更早建立的，請先把最新的 supabase/schema.sql 整份貼上執行一次
--  （可以重複執行，不會刪除任何資料），之後才能使用選項 B、C。選項 A、D 不需要。
-- ════════════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────────
--  【選項 A】重置卡片（預設，最常用）
--
--  做的事：
--    1. 清空全部流水帳（初始額度、消費、儲值、紀念日加值、禮物、沖銷）
--    2. 卡片還原成「尚未開卡」：清掉暱稱與問答資料、解除鎖定
--    3. 產生她的新通行碼（舊連結立刻失效）
--  不會動：後台通行碼、資料表與函式、金額設定、禮物清單。
--
--  結果：Results 會出現她的新通行碼 new_card_token。
--        新連結：https://你的網站/?k=<new_card_token>
--        後台連結不用換：https://你的網站/admin.html?k=<原本的 admin_token>
--        她重新開卡之後，才會再拿到初始額度。
-- ───────────────────────────────────────────────────────────────────────────
select app.reset_card() as new_card_token;


